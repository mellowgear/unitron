"""Text with a character map -> asm900 `db` lines (asm900 has no charmap; D7: a build step).

Charmap file lines: `char "a" 01` (text -> byte, longest match first), `cmd line FE string`
(a command word with a prefix byte, or `-` for none, taking a "string"), `cmd done FF`. `;` starts
a comment. In strings, `{XX}` is the byte XX. Text file lines: `cmd "string"` or `cmd`, `label:`,
`; comment`; anything else is an error.
"""
import re
from pathlib import Path


class CharmapError(Exception):
    pass


class Charmap:
    def __init__(self, path):
        self.chars, self.cmds = {}, {}
        for n, raw in enumerate(Path(path).read_text(encoding="utf-8").splitlines(), 1):
            s = raw.strip()
            if not s or s.startswith(";"):
                continue
            m = re.match(r'char\s+"((?:[^"]|"")+)"\s+([0-9A-Fa-f]{2})\s*(?:;.*)?$', s)
            if m:
                self.chars[m.group(1).replace('""', '"')] = int(m.group(2), 16)
                continue
            m = re.match(r"cmd\s+(\w+)\s+([0-9A-Fa-f]{2}|-)\s*(string)?\s*(?:;.*)?$", s)
            if m:
                self.cmds[m.group(1)] = (None if m.group(2) == "-" else int(m.group(2), 16), bool(m.group(3)))
                continue
            raise CharmapError(f"{path}:{n}: bad charmap line: {raw}")
        self.keys = sorted(self.chars, key=len, reverse=True)

    def encode(self, s):
        out, i = bytearray(), 0
        while i < len(s):
            m = re.match(r"\{([0-9A-Fa-f]{2})\}", s[i:])
            if m:
                out.append(int(m.group(1), 16))
                i += 4
                continue
            for k in self.keys:
                if s.startswith(k, i):
                    out.append(self.chars[k])
                    i += len(k)
                    break
            else:
                raise CharmapError(f"no character code for {s[i]!r}")
        return bytes(out)

    def command(self, line):
        """Bytes for `cmd "string"` / `cmd`, or None if the line is not a command."""
        m = re.match(r'^\s*([a-z_]+)(?:\s+"([^"]*)")?\s*(?:;.*)?$', line)
        if not m or m.group(1) not in self.cmds:
            return None
        pre, takes = self.cmds[m.group(1)]
        if takes != (m.group(2) is not None):
            raise CharmapError(f"`{m.group(1)}` " + ("needs a string" if takes else "takes no string"))
        return (bytes([pre]) if pre is not None else b"") + (self.encode(m.group(2)) if takes else b"")


def text_to_db(charmap, text, source=None):
    out = [f"; generated by unitron text from {source}: edit the text, not this file"] if source else []
    for n, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if not s or s.startswith(";"):
            out.append(line.rstrip())
            continue
        if re.fullmatch(r"[A-Za-z_.][\w.']*:", s):
            out.append(s)
            continue
        try:
            b = charmap.command(line)
        except CharmapError as e:
            raise CharmapError(f"{source or 'text'}:{n}: {e}") from None
        if b is None:
            raise CharmapError(f"{source or 'text'}:{n}: not a text command: {line.strip()}")
        for i in range(0, max(len(b), 1), 16):
            part = b[i:i + 16]
            note = f"\t; {s}" if i == 0 else ""
            out.append("\tdb\t" + ",".join(f"0x{x:02X}" for x in part) + note if part else f"\t; {s}")
    return "\n".join(out) + "\n"
