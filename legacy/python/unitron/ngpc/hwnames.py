def by_addr(kind=None):
    """{addr: NAME}, optionally only one kind."""
    return {e[0]: e[1] for e in NAMES if kind is None or e[3] == kind}


def by_name():
    """{NAME: addr} (bit names are in bits_by_name())."""
    return {e[1]: e[0] for e in NAMES}


def bits_by_name():
    """{NAME: (register addr, bit)}."""
    return {b[1]: (b[0], b[2]) for b in BITS}
