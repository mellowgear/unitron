"""Binary data -> asm900 `db` lines (generated data for `$include`)."""


def to_db(data, label=None, per_line=16, source=None):
    out = []
    if source:
        out.append(f"; generated by unitron bin2db from {source}: edit the source, not this file")
    if label:
        out.append(f"{label}:")
    for i in range(0, len(data), per_line):
        out.append("\tdb\t" + ",".join(f"0x{b:02X}" for b in data[i:i + per_line]))
    return "\n".join(out) + "\n"
