#include "bin2db.hpp"

#include <stdexcept>

namespace unitron {

std::string to_db(const Bytes& data, const std::string& label, int64_t per_line, const std::string& source) {
    static const char* HEX = "0123456789ABCDEF";
    std::string out;
    bool first = true;
    auto line = [&](const std::string& s) {
        if (!first) out += '\n';
        out += s;
        first = false;
    };
    if (!source.empty())
        line("; generated by unitron bin2db from " + source + ": edit the source, not this file");
    if (!label.empty()) line(label + ":");
    if (per_line < 1) throw std::runtime_error("bytes per line must be 1 or more, not " + std::to_string(per_line));
    {
        size_t step = static_cast<size_t>(per_line);
        for (size_t i = 0; i < data.size(); i += step) {
            std::string s = "\tdb\t";
            size_t end = data.size() - i < step ? data.size() : i + step;
            for (size_t k = i; k < end; k++) {
                if (k > i) s += ',';
                s += "0x";
                s += HEX[data[k] >> 4];
                s += HEX[data[k] & 15];
            }
            line(s);
        }
    }
    return out + "\n";
}

}  // namespace unitron
