// Writes syntaxes/asm900.tmLanguage.json from keywords.txt (the output of `unitron lsp --keywords`,
// asm900's reserved words from the assembler's own tables). Run: node scripts/gen-grammar.mjs
// Refresh keywords.txt first when unitron's tables change: unitron lsp --keywords > keywords.txt
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const kw = {};
for (const line of readFileSync(join(root, "keywords.txt"), "utf8").split("\n")) {
  const m = line.match(/^(\w+):(.*)$/);
  if (m) kw[m[1]] = m[2].trim().split(/\s+/).filter(Boolean);
}
const esc = (w) => w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
// longest first, so that alternation never stops at a prefix (QA0 before QA)
const alt = (ws) => [...ws].sort((a, b) => b.length - a.length || (a < b ? -1 : 1)).map(esc).join("|");
// asm900 identifiers: letters, digits, _ . and ' (WA', Routine.loop); keywords are case-insensitive
const B = "(?<![\\w.'$?])";
const E = "(?![\\w.'])";
const word = (ws, suffix = "") => `${B}(?i:(?:${alt(ws)})${suffix})${E}`;

const grammar = {
  $schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
  name: "asm900",
  scopeName: "source.asm900",
  comment: "Generated by scripts/gen-grammar.mjs from keywords.txt; do not edit by hand.",
  patterns: [
    { include: "#comment" },
    { include: "#preprocessor" },
    { include: "#macro" },
    { include: "#control" },
    { include: "#label" },
    { include: "#text" },
    { include: "#directive" },
    { include: "#mnemonic" },
    { include: "#macrocall" },
    { include: "#operands" },
  ],
  repository: {
    comment: {
      patterns: [
        { name: "comment.line.semicolon.asm900", match: ";.*$" },
        { name: "comment.line.double-slash.asm900", match: "//.*$" },
        { name: "comment.block.asm900", begin: "/\\*", end: "\\*/" },
      ],
    },
    string: {
      patterns: [
        {
          name: "string.quoted.double.asm900",
          begin: '"',
          // strings end at the line's end too, so an unterminated one doesn't colour the rest of the file
          end: '"(?!")|$',
          patterns: [
            { name: "constant.character.escape.asm900", match: '""' },
            { name: "constant.character.escape.asm900", match: "<[A-Za-z0-9_]+>|\\{[0-9A-Fa-f]{2}\\}" },
          ],
        },
        {
          name: "string.quoted.single.asm900",
          begin: "(?<![\\w.])'",
          end: "'|$",
          patterns: [{ name: "constant.character.escape.asm900", match: "\\\\." }],
        },
      ],
    },
    preprocessor: {
      patterns: [
        {
          match: "^\\s*(#\\s*include)\\s+(\"[^\"]*\"|<[^>]*>)",
          captures: { 1: { name: "keyword.control.directive.include.asm900" }, 2: { name: "string.quoted.other.include.asm900" } },
        },
        {
          match: "^\\s*(#\\s*define)\\s+([A-Za-z_]\\w*)",
          captures: { 1: { name: "keyword.control.directive.define.asm900" }, 2: { name: "entity.name.function.preprocessor.asm900" } },
        },
        {
          name: "keyword.control.directive.asm900",
          match: "^\\s*#\\s*(?:undef|ifdef|ifndef|if|elif|else|endif|error|line)\\b",
        },
      ],
    },
    macro: {
      patterns: [
        {
          match: "^\\s*(\\?macro)\\s+([A-Za-z_][\\w.]*)",
          captures: { 1: { name: "keyword.control.macro.asm900" }, 2: { name: "entity.name.function.macro.asm900" } },
        },
        { name: "keyword.control.macro.asm900", match: "^\\s*\\?endm\\b" },
        {
          match: "^\\s*(labels)\\s",
          captures: { 1: { name: "keyword.control.macro.asm900" } },
        },
        { name: "variable.parameter.macro.asm900", match: "\\?[A-Za-z_]\\w*" },
      ],
    },
    control: {
      match: `^\\s*(\\$(?i:${alt(kw.controls)}))${E}\\s*(\"[^\"]*\"|<[^>]*>)?`,
      captures: { 1: { name: "keyword.control.directive.asm900" }, 2: { name: "string.quoted.other.include.asm900" } },
    },
    label: {
      patterns: [
        // name equ / name section: a definition at any indent
        {
          match: `^\\s*([A-Za-z_.][\\w.']*)\\s+(?=(?i:equ|section)\\b)`,
          captures: { 1: { name: "entity.name.constant.asm900" } },
        },
        // a label with a colon, or a column-0 name without one
        {
          match: "^\\s*([A-Za-z_.][\\w.']*)(:)",
          captures: { 1: { name: "entity.name.function.label.asm900" }, 2: { name: "punctuation.separator.label.asm900" } },
        },
        {
          match: "^([A-Za-z_.][\\w.']*)(?=\\s|$)",
          captures: { 1: { name: "entity.name.function.label.asm900" } },
        },
      ],
    },
    text: {
      // the charmap's text commands ($charmap); slot pads fixed-size strings
      patterns: [
        {
          match: "^\\s*(text|line|page)\\s+(?=\")",
          captures: { 1: { name: "keyword.other.text.asm900" } },
        },
        { match: "^\\s*(done)\\s*(?=;|$)", captures: { 1: { name: "keyword.other.text.asm900" } } },
        { match: "^\\s*(slot)\\s", captures: { 1: { name: "keyword.other.text.asm900" } } },
      ],
    },
    directive: {
      name: "storage.type.directive.asm900",
      match: word(kw.directives),
    },
    mnemonic: {
      name: "keyword.operator.mnemonic.asm900",
      match: word(kw.mnemonics, "[BWL]?"),
    },
    macrocall: {
      // any other word at the start of an indented statement is a macro's name (?macro)
      match: `^\\s+(?!(?:\\?|(?i:(?:${alt(kw.mnemonics)})[BWL]?|${alt(kw.directives)}|text|line|page|done|slot|labels)(?![\\w.'])))([A-Za-z_][\\w.]*)(?=\\s|;|$)`,
      captures: { 1: { name: "entity.name.function.macro.call.asm900" } },
    },
    operands: {
      patterns: [
        { include: "#comment" },
        { include: "#string" },
        { name: "variable.language.register.asm900", match: `${B}(?i:${alt(kw.registers)})(?![\\w.])` },
        { name: "variable.language.control-register.asm900", match: word(kw.control_registers) },
        { name: "support.constant.condition.asm900", match: word(kw.conditions) },
        { name: "storage.modifier.asm900", match: word(kw.keywords) },
        { name: "constant.numeric.hex.asm900", match: `${B}0[xX][0-9A-Fa-f]+${E}` },
        { name: "constant.numeric.binary.asm900", match: `${B}0[yY][01]+${E}` },
        { name: "constant.numeric.suffixed.asm900", match: `${B}[0-9][0-9A-Fa-f]*[HhBbOoQqDd]${E}` },
        { name: "constant.numeric.decimal.asm900", match: `${B}[0-9]+${E}` },
        { name: "variable.language.location.asm900", match: "\\$(?![\\w])" },
        // the width operator expr:n ((label:24), 2:16)
        {
          match: "(:)(8|16|24|32)\\b",
          captures: { 1: { name: "keyword.operator.width.asm900" }, 2: { name: "constant.numeric.width.asm900" } },
        },
        { name: "keyword.operator.asm900", match: "<<|>>|[-+*/%&|^~=<>!]" },
        { name: "punctuation.separator.comma.asm900", match: "," },
        { name: "variable.other.symbol.asm900", match: "[A-Za-z_.][\\w.']*" },
      ],
    },
  },
};

writeFileSync(join(root, "syntaxes", "asm900.tmLanguage.json"), JSON.stringify(grammar, null, 2) + "\n");
console.log("wrote syntaxes/asm900.tmLanguage.json");
