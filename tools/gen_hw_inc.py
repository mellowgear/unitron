"""Write unitron/data/ngpc_hw.inc (asm900 equ lines) from unitron/ngpc/hwnames.py.

Usage: python tools/gen_hw_inc.py [--check]   (--check: exit 1 if the file is stale)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from unitron.ngpc import hwnames  # noqa: E402

OUT = ROOT / "unitron" / "data" / "ngpc_hw.inc"

SECTIONS = [
    ("io", "CPU on-chip I/O (Toshiba IO900H.H, TMP95C061F)"),
    ("sysram", "System work RAM (SNK SysPro, SysWork)"),
    ("vector", "Interrupt vectors (SNK SysPro); names are ours"),
    ("k2ge", "K2GE registers (SNK K2GEres, K2GETechRef)"),
    ("mem", "Memory areas (SNK SysLib, K2GETechRef, K2GEpal)"),
]


def hexval(v):
    return "0x%02X" % v if v < 0x100 else "0x%04X" % v


def render():
    out = [
        "; ngpc_hw.inc: NGPC hardware names. Generated by tools/gen_hw_inc.py from unitron/ngpc/hwnames.py; do not edit.",
        "; Sources: Toshiba IO900H.H and SNK developer docs, cited per line; see docs/hardware-names.md.",
    ]
    for kind, title in SECTIONS:
        out += ["", "; " + title]
        for addr, name, _size, k, cite, official in hwnames.NAMES:
            if k == kind:
                out.append("%s\tequ\t%s\t; %s (%s)" % (name, hexval(addr), cite, official))
    regs = hwnames.by_addr()
    out += ["", "; Bit numbers (mask = 1 << n)"]
    for reg, name, bit, cite, official in hwnames.BITS:
        out.append("%s\tequ\t%d\t; bit %d of %s; %s (%s)" % (name, bit, bit, regs[reg], cite, official))
    return "\n".join(out) + "\n"


def main(argv):
    text = render().encode("utf-8")
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_bytes() == text
        print("%s: %s" % (OUT.name, "up to date" if ok else "STALE"))
        return 0 if ok else 1
    OUT.write_bytes(text)
    print("wrote %s (%d names, %d bits)" % (OUT, len(hwnames.NAMES), len(hwnames.BITS)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
